#!/usr/bin/env python3
"""Extract build commands from the Linux From Scratch book sources.

Usage: lfs-extract.py <book-dir> <chapter-dir> <out-dir> <book-name>

Reads <book-dir>/<chapter-dir>/<chapter-dir>.xml (a git checkout of
https://github.com/lfs-book/lfs at the tag matching LFS_BOOK, with
./git-version.sh systemd already run), and writes one numbered build step
per section into <out-dir>, in book order. Test suites (remap="test") and
blocks the book marks as not to be run (role="nodump") are left out, as are
sysvinit-only parts. Blocks with <replaceable> placeholders are written as
comments so they can be filled in by hand.
"""
import re
import sys
from pathlib import Path

from lxml import etree

# Entities that come from the DocBook DTD, which we do not load.
DOCBOOK_ENTITIES = {
    "nbsp": "&#160;", "copy": "&#169;", "mdash": "&#8212;", "ndash": "&#8211;",
    "hellip": "&#8230;", "lsquo": "&#8216;", "rsquo": "&#8217;",
    "ldquo": "&#8220;", "rdquo": "&#8221;", "times": "&#215;",
}


# Packages whose tarball does not follow <productname>-<version>.
TARBALLS = {
    "Lz4": "lz4-*.tar.gz",
    "libelf": "elfutils-*.tar.bz2",
    "flit-core": "flit_core-*.tar.gz",
    "sqlite": "sqlite-autoconf-*.tar.gz",
    "tcl": "tcl*-src.tar.gz",
    "expect": "expect*.tar.gz",
}

# Values for the book's <replaceable> placeholders.
REPLACEMENTS = {
    "<xxx>": "UTC",          # time zone, glibc
    "<paper_size>": "A4",    # groff
}

# Steps in which the book expects some commands to fail harmlessly
# (strip prints errors for files that are not ELF objects).
LENIENT = {"stripping"}

# Text substitutions applied to every command block.
SUBSTITUTIONS = {
    "$(uname -m)-lfs-linux-gnu": "$SWISSMAN_TGT",
}


def load(path: Path) -> etree._Element:
    text = path.read_text()
    stub = "".join(f'<!ENTITY {k} "{v}">\n' for k, v in DOCBOOK_ENTITIES.items())
    text = re.sub(r'<!DOCTYPE (\w+) PUBLIC "[^"]*"\s*"[^"]*"\s*\[',
                  lambda m: f"<!DOCTYPE {m.group(1)} [\n{stub}", text, count=1)
    parser = etree.XMLParser(resolve_entities=True, load_dtd=True, no_network=True)
    root = etree.fromstring(text.encode(), parser, base_url=str(path))
    return root


def profiled_out(el) -> bool:
    for node in [el] + list(el.iterancestors()):
        rev = node.get("revision")
        if rev and "systemd" not in rev.split(";"):
            return True
    return False


def userinput_text(ui) -> tuple[str, bool]:
    """Return the block's text and whether it has an unknown placeholder."""
    unknown = False
    for rep in ui.iter("replaceable"):
        value = REPLACEMENTS.get(rep.text)
        if value is None:
            unknown = True
        else:
            rep.text = value
    text = "".join(ui.itertext())
    for old, new in SUBSTITUTIONS.items():
        text = text.replace(old, new)
    return text, unknown


def section_commands(sect):
    blocks = []
    for screen in sect.iter("screen"):
        if screen.get("role") == "nodump" or profiled_out(screen):
            continue
        for ui in screen.findall("userinput"):
            if ui.get("remap") == "test" or profiled_out(ui):
                continue
            text, editme = userinput_text(ui)
            blocks.append((text.strip("\n"), editme))
    return blocks


def main():
    book, chapter, out, book_name = sys.argv[1:5]
    book = Path(book)
    chapter_file = book / chapter / f"{chapter}.xml"
    chapter_root = load(chapter_file)
    # Resolve the chapter's XIncludes ourselves: each included section has
    # its own DOCTYPE that would otherwise pull in the DocBook DTD.
    xi = "{http://www.w3.org/2001/XInclude}include"
    sections = [load(chapter_file.parent / inc.get("href"))
                for inc in chapter_root.iter(xi)]
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)

    n = 0
    for sect in sections:
        if profiled_out(sect):
            continue
        blocks = section_commands(sect)
        if not blocks:
            continue
        n += 1
        title = " ".join("".join(sect.find("title").itertext()).split())
        pi = [p for p in sect.iter(etree.ProcessingInstruction)
              if p.target == "dbhtml" and "filename" in p.text]
        name = re.search(r'filename="([^"]+)\.html"', pi[0].text).group(1)
        product = sect.findtext("sect1info/productname")

        lines = [f"# {book_name}, {chapter}: {title}.",
                 "# Generated by tools/lfs-extract.py from the LFS book; do not edit by hand."]
        if name in LENIENT:
            lines += ["# The book expects harmless errors here.", "set +e"]
        if product:
            glob = TARBALLS.get(product)
            lines += [f"enter_src {product}" + (f" '{glob}'" if glob else ""),
                      "# The book refers to sources and patches as ../<file>.",
                      'ln -sf "$SOURCES"/* ..']
        for text, editme in blocks:
            lines.append("")
            if editme:
                lines.append("# NEEDS EDITING (placeholder in the book):")
                lines += ["# " + l for l in text.splitlines()]
            else:
                lines.append(text)
        (out / f"{n:03d}-{name}.sh").write_text("\n".join(lines) + "\n")
    print(f"wrote {n} steps to {out}")


if __name__ == "__main__":
    main()
